#!/usr/bin/env python3
"""Deterministic offline Go/TypeScript bindings for the portable policy package."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'skills/agent-memory'


def generate():
    names = ['SKILL.md'] + ['references/' + p.name for p in sorted((SOURCE / 'references').glob('*.md'))] + ['scripts/local_memory.py']
    assets = {name: (SOURCE / name).read_text() for name in names}
    version = re.search(r'Policy version: ([0-9.]+)', assets['SKILL.md']).group(1).rstrip('.')
    q = lambda value: json.dumps(value, ensure_ascii=False)
    guidance = assets['references/server-guidance.md'].strip()
    go = '// Code generated by scripts/generate-memory-policy.py; DO NOT EDIT.\npackage memorypolicy\n\n'
    go += f'const Version = {q(version)}\nconst Guidance = {q(guidance)}\nconst Core = {q(assets["SKILL.md"])}\n'
    go += 'var Assets = map[string]string{\n' + ''.join(f'\t{q(k)}: {q(v)},\n' for k, v in assets.items()) + '}\n'
    ts = '// Generated by scripts/generate-memory-policy.py; DO NOT EDIT.\n'
    ts += f'export const memoryPolicyVersion = {q(version)};\n'
    ts += f'export const memoryPolicyAssets: Record<string,string> = {json.dumps(assets, ensure_ascii=False, indent=2)};\n'
    return {ROOT / 'internal/memorypolicy/policy_generated.go': go, ROOT / 'frontend/src/lib/memoryPolicy.generated.ts': ts}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('outdated generated policy: ' + str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == '__main__':
    main()
